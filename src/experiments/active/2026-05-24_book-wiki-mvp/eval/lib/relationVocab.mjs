// 배정 프롬프트에 넣을 "이 축에는 무엇이 들어와야 하는가" 한 줄
export function memberSpec(relation) {
  const s = MEMBER_SPEC[relation];
  return s ? `${s.what} (최소 ${s.min}개)` : '이 축에 해당하는 키워드';
}

