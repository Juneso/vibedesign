// 순서가 의미를 갖는 관계 — 번호가 붙고 페이지 단조성 검증 대상이다.
export const ORDERED_RELATIONS = new Set(['통시', '과정', '인과']);

export const RELATION_NAMES = Object.keys(RELATIONS);

// 프롬프트 삽입용 가이드 블록. compact=true 면 이름·정의만.
export function relationGuide({ compact = false } = {}) {
  return RELATION_NAMES.map((k) => {
    const r = RELATIONS[k];
    if (compact) return `${k}: ${r.def}`;
    return `- ${k} — ${r.def}. 예: ${r.ex}${r.not ? ` / 주의: ${r.not}` : ''}`;
  }).join('\n');
}
