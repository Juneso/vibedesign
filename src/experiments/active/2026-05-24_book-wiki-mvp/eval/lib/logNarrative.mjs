// 최종 트리에서 "상위 → 축/단계 → 키워드" 골격을 역산한다.
// 로그가 세부를 안 남긴 옛 런에서도 결과 구조만큼은 보여주기 위한 경로다.
function treeShape(tree) {
  if (!tree?.nodes?.length) return null;
  const kids = (id) => tree.nodes.filter((n) => n.parentId === id && n.kind === 'concept');
  const sents = (id) => tree.nodes.filter((n) => n.parentId === id && n.kind === 'sentence').length;
  const root = tree.nodes.find((n) => n.kind === 'root');
  if (!root) return null;
  const lines = [];
  for (const top of kids(root.id)) {
    const mid = kids(top.id);
    if (!mid.length) { lines.push(`- ${top.title}${sents(top.id) ? ` (문장 ${sents(top.id)})` : ''} — 상위 없이 남은 키워드`); continue; }
    lines.push(`- **${top.title}**`);
    for (const m of mid) {
      const leaf = kids(m.id);
      const label = leaf.length ? leaf.map((l) => l.title).join(', ') : `문장 ${sents(m.id)}개`;
      lines.push(`  - ${m.title} ← ${label}`);
    }
  }
  return lines.length ? lines.join('\n') : null;
}

// run 객체(log[], dispatch, variant, counts, tree …) → 단계별 서사 마크다운
export function buildNarrative(run) {
  const sections = new Map(); // stage → [{tell, raw}]
  const misc = [];
  for (const line of run.log || []) {
    let hit = false;
    for (const r of RULES) {
      const m = line.match(r.re);
      if (!m) continue;
      const stage = r.stage;
      if (!sections.has(stage)) sections.set(stage, []);
      sections.get(stage).push({ tell: r.tell(m, line), raw: line, quiet: !!r.quiet });
      hit = true; break;
    }
    if (!hit && /^\[(plan|v10|v11)\]/.test(line)) misc.push(line);
  }

  // 원본 로그는 싣지 않는다 — 대시보드 md 렌더러가 <details> 를 모르는데다,
  // 서사가 로그를 이미 대체하므로 원본은 runs/*.json 의 log 필드로만 남긴다.
  let md = `## 이 실행에서 단계별로 일어난 일\n\n`;
  // 단계 제목은 굵은 글씨 한 줄로만 둔다 — 대시보드가 그 줄을 기준으로 단계를 나눈다.
  if (run.dispatch) md += `**⓪ 디스패치**\n\n- ${run.dispatch} → **${run.variant}** 경로로 보냈다.\n\n`;

  for (const [stage, items] of sections) {
    md += `**${stage}**\n\n`;
    const loud = items.filter((i) => !i.quiet);
    const quiet = items.filter((i) => i.quiet);
    for (const i of loud) md += `- ${i.tell}\n`;
    if (quiet.length) md += `- 만들어진 키워드 ${quiet.length}개: ${quiet.map((i) => i.raw.match(/"(.+?)"/)?.[1]).filter(Boolean).join(', ')}\n`;
    md += `\n`;
  }
  // 번역 규칙이 없는 로그도 조용히 버리지 않는다 — 규칙 보강이 필요하다는 신호다.
  if (misc.length) {
    md += `**그 밖의 기록**\n\n`;
    for (const l of misc) md += `- ${l.replace(/^\[[^\]]+\]\s*/, '')}\n`;
    md += `\n`;
  }

  // 트리에서 역산한 최종 구조 — 로그에 세부가 없는 옛 런도 이 단계는 채워진다.
  const shape = treeShape(run.tree);
  if (shape) md += `**⑧ 만들어진 구조**\n\n${shape}\n`;

  if (run.counts) {
    const c = run.counts;
    md += `**마무리 숫자**\n\n- 개념 ${c.concepts ?? (c.stages + c.keywords)}개 · 문장 ${c.sentences}개 · 메모 커버 ${c.coveredMemos}/${run.nMemos}\n`;
  }
  return md;
}
